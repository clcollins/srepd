func TestApprovalsStrip_RenderShowsCount(t *testing.T) {
	strip := newApprovalsStrip()
	assert.Equal(t, "", strip.Render(80))

	strip.Add(Ask{Kind: AskDraftNote, Title: "Note"})
	strip.Add(Ask{Kind: AskSuggestedCommand, Title: "Cmd"})

	rendered := strip.Render(80)
	assert.NotEmpty(t, rendered)
	width := lipgloss.Width(rendered)
	require.Greater(t, width, 0, "strip must have non-zero width")
}

