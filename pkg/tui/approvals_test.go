func TestApprovalsStrip_RenderExpandedShowsAsks(t *testing.T) {
	strip := newApprovalsStrip()
	strip.Add(Ask{Kind: AskDraftNote, Title: "Draft note about cluster"})
	strip.Add(Ask{Kind: AskSuggestedCommand, Title: "oc get nodes"})

	rendered := strip.RenderExpanded(80)
	assert.Contains(t, rendered, "Pending Approvals")
	assert.Contains(t, rendered, "[Note]")
	assert.Contains(t, rendered, "[Command]")
	assert.Contains(t, rendered, "Draft note about cluster")
	assert.Contains(t, rendered, "oc get nodes")
	assert.Contains(t, rendered, "Accept")
	assert.Contains(t, rendered, "Dismiss")
}

func TestApprovalsStrip_MoveSelection(t *testing.T) {
	strip := newApprovalsStrip()
	strip.Add(Ask{Kind: AskDraftNote, Title: "Note 1"})
	strip.Add(Ask{Kind: AskDraftNote, Title: "Note 2"})
	strip.Add(Ask{Kind: AskDraftNote, Title: "Note 3"})

	assert.Equal(t, 0, strip.selected)

	strip.MoveDown()
	assert.Equal(t, 1, strip.selected)

	strip.MoveDown()
	assert.Equal(t, 2, strip.selected)

	strip.MoveDown()
	assert.Equal(t, 2, strip.selected, "must not go past the end")

	strip.MoveUp()
	assert.Equal(t, 1, strip.selected)

	strip.MoveUp()
	assert.Equal(t, 0, strip.selected)

	strip.MoveUp()
	assert.Equal(t, 0, strip.selected, "must not go below zero")
}

func TestApprovalsStrip_AcceptSelected(t *testing.T) {
	strip := newApprovalsStrip()
	var called string
	strip.Add(Ask{Kind: AskDraftNote, Title: "Note 1",
		Action: func() tea.Cmd { called = "note1"; return nil }})
	strip.Add(Ask{Kind: AskSuggestedCommand, Title: "Cmd 1",
		Action: func() tea.Cmd { called = "cmd1"; return nil }})

	strip.selected = 1
	strip.Accept(strip.selected)
	assert.Equal(t, "cmd1", called, "must accept the selected ask")
	assert.Equal(t, 1, strip.Count())
}
