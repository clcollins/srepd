func TestApprovalsStrip_AddAndCount(t *testing.T) {
	strip := newApprovalsStrip()
	assert.Equal(t, 0, strip.Count())

	strip.Add(Ask{Kind: AskDraftNote, Title: "Draft note"})
	assert.Equal(t, 1, strip.Count())

	strip.Add(Ask{Kind: AskSuggestedCommand, Title: "Run oc get nodes"})
	assert.Equal(t, 2, strip.Count())
}

func TestApprovalsStrip_AcceptInvokesAction(t *testing.T) {
	strip := newApprovalsStrip()
	var called int
	strip.Add(Ask{
		Kind:  AskDraftNote,
		Title: "Post note",
		Action: func() tea.Cmd {
			called++
			return nil
		},
	})

	cmd := strip.Accept(0)
	assert.Nil(t, cmd)
	assert.Equal(t, 1, called, "Action must be invoked exactly once")
	assert.Equal(t, 0, strip.Count(), "Ask must be removed after accept")
}

func TestApprovalsStrip_DismissRemoves(t *testing.T) {
	strip := newApprovalsStrip()
	strip.Add(Ask{Kind: AskDraftNote, Title: "Note 1"})
	strip.Add(Ask{Kind: AskSuggestedCommand, Title: "Cmd 1"})

	strip.Dismiss(0)
	assert.Equal(t, 1, strip.Count())
	assert.Equal(t, "Cmd 1", strip.asks[0].Title)
}

